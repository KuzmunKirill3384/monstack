'''Задание 1.
Сделать датчик случайных чисел, который генерирует “0” или “1” с заданными
вероятностями (можно взять стандартный датчик,
выдающий числа на промежутке [0;1] и рассмотреть границу -
число p из этого промежутка; тогда если выпашее число меньше
p выбирается “0”, иначе “1”; нетудно понять, что “0” будет
выбираться с вероятностью p, а “1” - с вероятностью 1-p).
Далее число 0 будет означать выбор 1-ой (красной) строки/столбца,
а число “1” - выбор второй (синей) строки/столбца.'''

import random

def generate_choice(p):
    """
    Генерирует 0 или 1 на основе заданной вероятности p.

    :param p: Вероятность выбора "0" (0 <= p <= 1).
    :return: 0 или 1
    """
    if random.random() < p:
        return 0  # Выбираем "0" с вероятностью p
    else:
        return 1  # Выбираем "1" с вероятностью 1-p

# Пример использования
p = 0.7  # Вероятность выбора "0"
n = 1000000  # Количество генераций

results = [generate_choice(p) for _ in range(n)]
print(f"Сгенерированные числа (0 и 1) с вероятностью p={p}:\n{results}")
print(f"Количество 0 = {results.count(0)/len(results)}")
print(f"Количество 1 = {results.count(1)/len(results)}")